import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../new-tab-launcher/claude-app-creative-library.js',import.meta.url),'utf8');
const box={window:{addEventListener(){},URL:{revokeObjectURL(){}}}};
vm.runInNewContext(source,box);
const api=box.window.CCCreativeLibrary;
assert.ok(api,'Creative Library must expose its lazy entry point');
const t=api.test;
assert.equal(t.classifyFile({name:'reference.png',type:'image/png'}),'image');
assert.equal(t.classifyFile({name:'clip.webm',type:'video/webm'}),'video');
assert.equal(t.classifyFile({name:'notes.md',type:''}),'text');
assert.equal(t.classifyFile({name:'paper.pdf',type:'application/pdf'}),'document');
assert.equal(t.classifyFile({name:'archive.zip',type:'application/zip'}),'');
assert.equal(t.validateFile({name:'photo.jpg',type:'image/jpeg',size:1024}).ok,true);
assert.equal(t.validateFile({name:'movie.mp4',type:'video/mp4',size:51*1024*1024}).ok,false);
assert.equal(t.validateFile({name:'empty.txt',type:'text/plain',size:0}).ok,false);
assert.equal(t.validateFile({name:'script.js',type:'text/javascript',size:20}).ok,false);
assert.deepEqual(Array.from(t.normalizeTags('Editorial, colour, editorial, slow   pacing, , visual')),['Editorial','colour','slow pacing','visual']);
assert.equal(Array.from(t.normalizeTags(Array.from({length:20},(_,i)=>'tag'+i))).length,12);
assert.equal(t.matchesAsset({name:'Poster Study',description:'Warm palette',tags:['cinematic'],analysis:''},{query:'cinematic'}),true);
assert.equal(t.matchesAsset({name:'Poster Study',description:'Warm palette',tags:[],analysis:''},{type:'video'}),false);
assert.equal(t.matchesAsset({name:'Poster Study',description:'Warm palette',tags:[],analysis:''},{collectionId:'other'}),false);
assert.equal(t.formatBytes(0),'0 B');
assert.equal(t.formatBytes(1024),'1.0 KB');
assert.equal(t.maxAssets,500);
assert.equal(t.maxImportBatch,8);
assert.equal(t.maxTextAnalysis,12000);
assert.match(source,/indexedDB\.open/);
assert.match(source,/createObjectStore\('blobs'/);
assert.match(source,/video\.preload='metadata'/);
assert.match(source,/confirm\('Send up to the first 12,000 characters/);
assert.doesNotMatch(source,/new\s+FileReader\s*\(/);
assert.doesNotMatch(source,/createImageBitmap\s*\(/);
console.log('Creative Library validation, limits, filtering and privacy-contract tests passed.');