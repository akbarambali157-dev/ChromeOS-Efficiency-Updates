import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('new-tab-launcher/claude-app-workspaces.js','utf8');
const html=fs.readFileSync('new-tab-launcher/claude-app.html','utf8');
const css=fs.readFileSync('new-tab-launcher/claude-app.css','utf8');
assert.match(html,/id="paneReference"[^>]*aria-label="Reference Lab"/,'navigation button');
assert.match(html,/id="referenceWorkspace" data-workspace="reference" hidden/,'Reference Lab workspace shell');
assert.match(html,/id="referenceSearch"/,'search field');
assert.match(html,/id="referenceRefresh"/,'refresh button');
assert.match(html,/id="referenceClear"/,'clear-selection button');
assert.match(html,/id="referenceAttach"/,'attach button');
assert.match(html,/Nothing is uploaded automatically/,'privacy explanation');
assert.match(source,/function loadReferenceLibrary\(force\)/,'local library loader');
assert.match(source,/CCCreativeLibrary\.listReferences\(\)/,'uses local reference store');
assert.match(source,/referenceSelected\.length>=6/,'selection cap enforced');
assert.match(source,/slice\(0,4000\)/,'attached context bounded');
assert.match(source,/Selected Reference Lab context/,'references included in AI Team prompt context');
assert.match(source,/function clearReferences/,'selection and context clear control');
assert.match(source,/paneReference:'reference'/,'workspace navigation wired');
assert.match(source,/loadReferenceLibrary\(false\)/,'lazy load on opening workspace');
assert.match(css,/\.reference-item/,'selection cards styled');
const window={addEventListener(){}};vm.runInNewContext(source,{window});
const build=window.CCWorkspaces.test.buildReferenceContext;
const chosen=Array.from({length:7},(_,i)=>({id:String(i),name:'Ref '+i,type:'text',tags:['tag'+i],description:'D'.repeat(1000),analysis:'A'.repeat(1000)}));
const ctx=build(chosen);
assert.ok(ctx.length<=4000,'context must stay at or under 4000 characters');
assert.match(ctx,/\[1\] Ref 0/);assert.match(ctx,/\[6\] Ref 5/);assert.doesNotMatch(ctx,/\[7\] Ref 6/,'only first six references are included');
assert.match(ctx,/Tags: tag0/);assert.match(ctx,/Description:/);assert.match(ctx,/Analysis:/);
assert.equal(build([]),'','empty selection yields no context');
console.log('Reference Lab navigation, local-only loader, selection limit, clear/attach and context-size tests passed.');
