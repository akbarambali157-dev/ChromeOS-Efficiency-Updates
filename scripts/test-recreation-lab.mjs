import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../new-tab-launcher/claude-app-recreation-lab.js',import.meta.url),'utf8');
const box={window:{},document:{getElementById(){return null;}}};
vm.runInNewContext(source,box);
const api=box.window.CCRecreationLab;
assert.ok(api,'Recreation Lab must expose a lazy entry point');
assert.equal(typeof api.open,'function');
assert.equal(typeof api.suspend,'function');
assert.equal(api.test.maxReferences,5);
assert.equal(api.test.maxCriteria,8);
assert.deepEqual(Array.from(api.test.criteriaList('clarity\nHierarchy\nclarity, accessibility')),['clarity','Hierarchy','accessibility']);
const clean=api.test.cleanReference({id:'r1',name:'Poster',type:'image',description:'warm',tags:['editorial'],analysis:'summary',blob:'must-not-escape'});
assert.deepEqual(JSON.parse(JSON.stringify(clean)),{id:'r1',name:'Poster',type:'image',description:'warm',tags:['editorial'],analysis:'summary'});
assert.match(source,/No original image, video, PDF or other file contents are uploaded/);
assert.match(source,/g\.CCCreativeLibrary\.openCatalog/);
assert.match(source,/g\.CCCreativeLibrary\.saveExperiment/);
assert.match(source,/g\.CCCreativeLibrary\.deleteExperiment/);
assert.match(source,/return refresh\(\)\.then/,'opening the lab should use one bounded catalog refresh');
assert.doesNotMatch(source,/Promise\.all\(\[g\.CCCreativeLibrary\.listReferences/,'avoid duplicate IndexedDB catalog reads');
assert.match(source,/ui\.generate\.disabled=false;ui\.save\.disabled=false/,'controls must recover after reopening the workspace');
assert.match(source,/confirm\(disclosure\+' Continue\?'\)/,'each provider run must require an explicit consent confirmation');
assert.match(source,/style profile name, description and guidance/,'the consent notice must disclose all selected profile fields');
const library=fs.readFileSync(new URL('../new-tab-launcher/claude-app-creative-library.js',import.meta.url),'utf8');
const app=fs.readFileSync(new URL('../new-tab-launcher/claude-app.js',import.meta.url),'utf8');
const workspace=fs.readFileSync(new URL('../new-tab-launcher/claude-app-workspaces.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../new-tab-launcher/claude-app.html',import.meta.url),'utf8');
const manifest=JSON.parse(fs.readFileSync(new URL('../new-tab-launcher/manifest.json',import.meta.url),'utf8'));
assert.match(library,/VERSION=2/,'existing IndexedDB data must migrate additively');
assert.match(library,/createObjectStore\('experiments'/);
assert.match(library,/saveExperiment:saveExperiment/);
assert.match(library,/listReferences:listReferences/);
assert.match(library,/listProfiles:listProfiles/);
assert.match(library,/deleteExperiment:deleteExperiment/);
assert.match(library,/scores:Array\.isArray\(record\.scores\)/,'saved scorecards must be bounded and persisted');
assert.match(source,/function renderScorecard/,'each user criterion must have a 1–5 scorecard');
assert.match(app,/runCreativeExperiment: function/);
assert.match(workspace,/function loadRecreationLab/);
assert.match(workspace,/if\(name==='recreation'\)loadRecreationLab\(\)/);
assert.match(html,/id="paneRecreation"/);
assert.match(html,/id="recreationWorkspace"/);
assert.equal(manifest.version,'5.7.0');
assert.equal(manifest.minimum_chrome_version,'103');
assert.doesNotMatch(source,/FileReader|createImageBitmap|URL\.createObjectURL/);
console.log('Recreation Lab structure, bounded selections and privacy-contract tests passed.');
